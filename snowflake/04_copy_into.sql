USE DATABASE WALMART_E2E;
USE SCHEMA RAW;
USE WAREHOUSE WALMART_WH;

COPY INTO DEPARTMENT (STORE, DEPT, DATE, WEEKLY_SALES, ISHOLIDAY)
  FROM @WALMART_S3_STAGE/department.csv
  FILE_FORMAT = (FORMAT_NAME = WALMART_CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO STORES (STORE, TYPE, SIZE)
  FROM @WALMART_S3_STAGE/stores.csv
  FILE_FORMAT = (FORMAT_NAME = WALMART_CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO FACT (STORE, DATE, TEMPERATURE, FUEL_PRICE, MARKDOWN1, MARKDOWN2, MARKDOWN3, MARKDOWN4, MARKDOWN5, CPI, UNEMPLOYMENT, ISHOLIDAY)
  FROM @WALMART_S3_STAGE/fact.csv
  FILE_FORMAT = (FORMAT_NAME = WALMART_CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

-- Expect: DEPARTMENT=421570, STORES=45, FACT=8190
SELECT 'DEPARTMENT' AS TBL, COUNT(*) FROM DEPARTMENT
UNION ALL SELECT 'STORES', COUNT(*) FROM STORES
UNION ALL SELECT 'FACT', COUNT(*) FROM FACT;
