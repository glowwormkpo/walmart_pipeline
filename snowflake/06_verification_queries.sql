USE DATABASE WALMART_E2E;
USE WAREHOUSE WALMART_WH;

-- Row counts should match the profiled source files
SELECT 'RAW.DEPARTMENT' AS T, COUNT(*) AS N FROM RAW.DEPARTMENT      -- expect 421570
UNION ALL SELECT 'RAW.STORES', COUNT(*) FROM RAW.STORES              -- expect 45
UNION ALL SELECT 'RAW.FACT', COUNT(*) FROM RAW.FACT                  -- expect 8190
UNION ALL SELECT 'CORE.WALMART_DATE_DIM', COUNT(*) FROM CORE.WALMART_DATE_DIM      -- expect 182
UNION ALL SELECT 'CORE.WALMART_STORE_DIM (current)', COUNT(*) FROM CORE.WALMART_STORE_DIM WHERE IS_CURRENT   -- expect 3331
UNION ALL SELECT 'CORE.WALMART_FACT_TABLE', COUNT(*) FROM CORE.WALMART_FACT_TABLE                          -- expect 421570
UNION ALL SELECT 'CORE.WALMART_STORE_CONDITIONS_FACT', COUNT(*) FROM CORE.WALMART_STORE_CONDITIONS_FACT;   -- expect 8190

-- Grain checks: both should return 0 (no duplicate keys, so no fan-out)
SELECT COUNT(*) - COUNT(DISTINCT STORE_ID, DEPT_ID, DATE_ID) AS DUP_KEYS_DEPT_FACT FROM CORE.WALMART_FACT_TABLE;
SELECT COUNT(*) - COUNT(DISTINCT STORE_ID, DATE_ID) AS DUP_KEYS_STORE_CONDITIONS FROM CORE.WALMART_STORE_CONDITIONS_FACT;

-- Fact rows with no matching store_dim version (should be 0)
SELECT COUNT(*) AS UNMATCHED_STORE_DIM FROM CORE.WALMART_FACT_TABLE WHERE STORE_DIM_KEY IS NULL;

-- Reconciliation to source: each DIFF should be 0 (within rounding)
SELECT
  ROUND((SELECT SUM(STORE_WEEKLY_SALES) FROM CORE.WALMART_FACT_TABLE) - (SELECT SUM(WEEKLY_SALES) FROM RAW.DEPARTMENT), 2) AS SALES_DIFF,
  ROUND((SELECT SUM(TOTAL_MARKDOWN) FROM CORE.WALMART_STORE_CONDITIONS_FACT)
      - (SELECT SUM(COALESCE(MARKDOWN1,0)+COALESCE(MARKDOWN2,0)+COALESCE(MARKDOWN3,0)+COALESCE(MARKDOWN4,0)+COALESCE(MARKDOWN5,0)) FROM RAW.FACT), 2) AS MARKDOWN_DIFF;

-- Top-line: total weekly sales should be ~$6,737,218,987; total markdown ~$72.7M
-- (~$40.3M of it falls inside the sales window, i.e. dates on or before 2012-10-26)
SELECT ROUND(SUM(STORE_WEEKLY_SALES), 2) AS TOTAL_WEEKLY_SALES FROM CORE.WALMART_FACT_TABLE;
SELECT ROUND(SUM(TOTAL_MARKDOWN), 2) AS TOTAL_MARKDOWN_ALL_DATES FROM CORE.WALMART_STORE_CONDITIONS_FACT;
